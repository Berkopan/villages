let language = (() => {
  try {
    const saved = globalThis.localStorage?.getItem(STORAGE_KEY);
    if (SUPPORTED_LANGUAGES.includes(saved)) return saved;
  } catch { /* Private browsing and restricted storage are supported. */ }
  return (globalThis.navigator?.language || 'tr').toLowerCase().startsWith('tr') ? 'tr' : 'en';
})();

export function getLanguage() { return language; }
export function setLanguage(next) {
  if (!SUPPORTED_LANGUAGES.includes(next)) return false;
  language = next;
  try { globalThis.localStorage?.setItem(STORAGE_KEY, next); } catch { /* Still usable without storage. */ }
  return true;
}

