function english(value) {
  if (Object.hasOwn(translations, value)) return translations[value];
  for (const [pattern, formatter] of patterns) {
    const match = value.match(pattern);
    if (match) return formatter(match);
  }
  return value;
}

export function t(value) {
  const original = String(value ?? '');
  if (language !== 'en') return original;
  const match = original.match(/^(\s*)([\s\S]*?)(\s*)$/);
  return match[1] + english(match[2]) + match[3];
}

// Static DOM nodes keep their original Turkish text so switching back is lossless.
// Live values (simulation names, counters and inspector/chronicle HTML) are excluded.
const originals = new WeakMap();
const dynamicSelectors = '#seed-name, #save-status, #autosave-status, #stat-population, #stat-settlements, #stat-food, #stat-happiness, #population-trend, #calendar-year, #calendar-day, #pause-button, #live-label, #map-weather, #active-tool-text, #follow-label, #map-status-text, #performance-status, #mobile-inspector-label, #chronicle-count, #chronicle-events, #inspector-content, #inspector-title, #inspector-eyebrow, #inspector-close, #population-output, #aggression-output, #toast-region, #sound-button';
const attributes = ['aria-label', 'title', 'placeholder', 'content'];

function excluded(element) {
  return element?.closest?.(dynamicSelectors + ', script, style, [contenteditable="true"]');
}
function translateNodes(root, preserve) {
  const doc = root.ownerDocument || root;
  const walker = doc.createTreeWalker(root, 4);
  let node;
  while ((node = walker.nextNode())) {
    if (preserve && excluded(node.parentElement)) continue;
    if (!node.nodeValue.trim()) continue;
    const original = preserve ? (originals.get(node) ?? node.nodeValue) : node.nodeValue;
    if (preserve && !originals.has(node)) originals.set(node, original);
    node.nodeValue = t(original);
  }
  const elements = [root, ...root.querySelectorAll('*')].filter(el => el.nodeType === 1);
  for (const element of elements) {
    if (preserve && excluded(element)) continue;
    for (const attribute of attributes) {
      if (!element.hasAttribute(attribute)) continue;
      let entries = preserve ? originals.get(element) : null;
      if (!entries) {
        entries = {};
        if (preserve) originals.set(element, entries);
      }
      const original = preserve && Object.hasOwn(entries, attribute) ? entries[attribute] : element.getAttribute(attribute);
      if (preserve && !Object.hasOwn(entries, attribute)) entries[attribute] = original;
      element.setAttribute(attribute, t(original));
    }
  }
}

export function localizeStatic(documentRoot) {
  translateNodes(documentRoot, true);
  documentRoot.documentElement.lang = language;
}

export function localizeFresh(root) {
  if (language === 'en') translateNodes(root, false);
}
